// Several countries can share one dial code. When a pasted number matches, this is the one shown.
export const PRIMARY_FOR_DIAL = { 1: 'US', 7: 'RU', 39: 'IT', 44: 'GB', 47: 'NO', 61: 'AU', 212: 'MA', 262: 'RE', 358: 'FI', 590: 'GP', 599: 'CW' };

// National numbers that really do start with 0 even in international form, so the 0 must be kept.
export const KEEPS_LEADING_ZERO = new Set(['IT', 'VA', 'SM', 'CI']);

const BY_ISO = new Map(COUNTRIES.map((c) => [c[0], c]));
export const countryByIso = (iso) => BY_ISO.get(String(iso || '').toUpperCase()) || BY_ISO.get(DEFAULT_COUNTRY);
export const dialForIso = (iso) => countryByIso(iso)[2];
export const nameForIso = (iso) => countryByIso(iso)[1];
export const flag = (iso) => [...String(iso || '').toUpperCase()].map((ch) => String.fromCodePoint(127397 + ch.charCodeAt(0))).join('');
// "+1", "+234", "+1 876": how a dial code is shown.
export const dialLabel = (iso) => { const d = dialForIso(iso); return d.length > 1 && d[0] === '1' && d.length === 4 ? `+1 ${d.slice(1)}` : `+${d}`; };

const DIALS = new Map();
for (const c of COUNTRIES) { if (!DIALS.has(c[2])) DIALS.set(c[2], []); DIALS.get(c[2]).push(c[0]); }
export const MAX_DIAL_LENGTH = Math.max(...[...DIALS.keys()].map((d) => d.length));

// Longest dial code that starts these digits -> the country to show for it.
export function countryForDigits(digits) {
  const s = String(digits || '');
  for (let len = Math.min(MAX_DIAL_LENGTH, s.length); len >= 1; len -= 1) {
    const list = DIALS.get(s.slice(0, len));
    if (list) return { iso: PRIMARY_FOR_DIAL[s.slice(0, len)] && list.includes(PRIMARY_FOR_DIAL[s.slice(0, len)]) ? PRIMARY_FOR_DIAL[s.slice(0, len)] : list[0], dial: s.slice(0, len) };
  }
  return null;
}
